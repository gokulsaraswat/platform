import { readFileSync, writeFileSync, existsSync } from 'node:fs';

const here = (p) => new URL(p, import.meta.url);
const src = JSON.parse(readFileSync(here('../src/v2/flavors.json'), 'utf8'));
const { shared, flavors } = src;
const names = Object.keys(flavors);
const HEADER = '/* Generated by packages/ui/scripts/gen.mjs from src/v2/flavors.json. Do not edit by hand. */\n';

const decl = (entries, indent = '  ') => entries.map(([k, v]) => `${indent}${k}: ${v};`).join('\n');
const block = (selectors, body) => `${selectors.join(',\n')} {\n${body}\n}\n`;

const colorVars = (mode) =>
  Object.entries(mode).map(([k, v]) => (k === 'shadow-color' ? ['--gk-shadow-color', v] : [`--gk-color-${k}`, v]));

const staticVars = (f) => [
  ...Object.entries(f.font).map(([k, v]) => [`--gk-font-${k}`, v]),
  ...Object.entries(f.text).map(([k, v]) => [`--gk-text-${k}`, v]),
  ...Object.entries(f.leading).map(([k, v]) => [`--gk-leading-${k}`, v]),
  ...Object.entries(f.weight).map(([k, v]) => [`--gk-weight-${k}`, v]),
  ...Object.entries(f.tracking).map(([k, v]) => [`--gk-tracking-${k}`, v]),
  ...Object.entries(f.radius).map(([k, v]) => [`--gk-radius-${k}`, v]),
  ['--gk-control-h', f['control-h']],
  ['--gk-press', f.press],
];

const sharedVars = [
  ...Object.entries(shared.space).map(([k, v]) => [`--gk-space-${k}`, v]),
  ...Object.entries(shared.motion).map(([k, v]) => [`--gk-${k}`, v]),
  ...Object.entries(shared.z).map(([k, v]) => [`--gk-z-${k}`, v]),
  ['--gk-touch-min', shared['touch-min']],
  ['--gk-measure', shared.measure],
  ['--gk-shadow-1', '0 1px 2px rgb(var(--gk-shadow-color) / calc(0.07 * var(--gk-shadow-k)))'],
  ['--gk-shadow-2', '0 1px 2px rgb(var(--gk-shadow-color) / calc(0.06 * var(--gk-shadow-k))), 0 6px 16px -4px rgb(var(--gk-shadow-color) / calc(0.12 * var(--gk-shadow-k)))'],
  ['--gk-shadow-3', '0 4px 8px rgb(var(--gk-shadow-color) / calc(0.08 * var(--gk-shadow-k))), 0 18px 40px -10px rgb(var(--gk-shadow-color) / calc(0.24 * var(--gk-shadow-k)))'],
];

const flavorSel = (n) => (n === names[0] ? [':root', `[data-gk-flavor="${n}"]`] : [`[data-gk-flavor="${n}"]`]);
const darkSel = (n) => [
  ...(n === names[0] ? [':root.dark', ':root[data-gk-theme="dark"]'] : []),
  `.dark [data-gk-flavor="${n}"]`, `[data-gk-flavor="${n}"].dark`,
  `[data-gk-theme="dark"] [data-gk-flavor="${n}"]`, `[data-gk-flavor="${n}"][data-gk-theme="dark"]`,
];
const systemSel = (n) => [
  ...(n === names[0] ? [':root[data-gk-theme="system"]'] : []),
  `[data-gk-theme="system"] [data-gk-flavor="${n}"]`, `[data-gk-flavor="${n}"][data-gk-theme="system"]`,
];

function tokensCss() {
  let out = HEADER + `/*
 * @gokulsaraswat/ui v2 tokens. Additive: v1 tokens.css is untouched and can be loaded alongside.
 * Flavor: data-gk-flavor="${names.join('|')}" on <html> (or any subtree). No attribute = ${names[0]}.
 * Theme: light by default; dark via class "dark" (v1 convention) or data-gk-theme="dark"; data-gk-theme="system" follows the OS.
 */\n`;
  out += block([':root'], decl([...sharedVars, ['--gk-shadow-k', '1']]));
  for (const n of names) {
    const f = flavors[n];
    out += '\n' + block(flavorSel(n), decl([['color-scheme', 'light'], ...staticVars(f), ...colorVars(f.light), ['--gk-shadow-k', '1']]));
  }
  for (const n of names) {
    out += '\n' + block(darkSel(n), decl([['color-scheme', 'dark'], ...colorVars(flavors[n].dark), ['--gk-shadow-k', '2.5']]));
  }
  out += '\n@media (prefers-color-scheme: dark) {\n';
  for (const n of names) {
    out += block(systemSel(n).map((s) => `  ${s}`), decl([['color-scheme', 'dark'], ...colorVars(flavors[n].dark), ['--gk-shadow-k', '2.5']], '    ')).replace(/^}/m, '  }');
  }
  out += '}\n\n@media (prefers-reduced-motion: reduce) {\n  :root {\n' +
    decl(Object.keys(shared.motion).filter((k) => k.startsWith('dur-')).map((k) => [`--gk-${k}`, '0ms']), '    ') + '\n  }\n}\n';
  return out;
}

function tailwindCss() {
  const f = flavors[names[0]];
  const map = [
    ...Object.keys(f.light).filter((k) => k !== 'shadow-color').map((k) => [`--color-gk-${k}`, `var(--gk-color-${k})`]),
    ...Object.keys(f.font).map((k) => [`--font-gk-${k}`, `var(--gk-font-${k})`]),
    ...Object.keys(f.text).map((k) => [`--text-gk-${k}`, `var(--gk-text-${k})`]),
    ...Object.keys(f.radius).map((k) => [`--radius-gk-${k}`, `var(--gk-radius-${k})`]),
    ...[1, 2, 3].map((i) => [`--shadow-gk-${i}`, `var(--gk-shadow-${i})`]),
    ...Object.keys(shared.motion).filter((k) => k.startsWith('ease-')).map((k) => [`--ease-gk-${k.slice(5)}`, `var(--gk-${k})`]),
  ];
  return HEADER + `/*
 * Tailwind v4 mapping for v2/tokens.css. Import after \`@import "tailwindcss";\` and v2/tokens.css.
 * Utilities are gk-namespaced so they never collide with v1: bg-gk-surface, text-gk-text-muted, rounded-gk-md, shadow-gk-2.
 */
@theme inline {
${decl(map)}
}
`;
}

function flavorsTs() {
  const pick = (f) => ({ label: f.label, use: f.use, font: f.font, text: f.text, radius: f.radius, controlH: f['control-h'], light: f.light, dark: f.dark });
  const data = Object.fromEntries(names.map((n) => [n, pick(flavors[n])]));
  return `/* Generated by packages/ui/scripts/gen.mjs from src/v2/flavors.json. Do not edit by hand. */
/** Raw v2 values for code that cannot read CSS variables (canvas, charts, native status bars, meta theme-color). */
export const flavors = ${JSON.stringify(data, null, 2)} as const;

export type FlavorName = keyof typeof flavors;
export type ColorToken = keyof (typeof flavors)['${names[0]}']['light'];
export const flavorNames = ${JSON.stringify(names)} as const satisfies readonly FlavorName[];
`;
}

function briefBlock() {
  let md = '<!-- RAW:START (generated by packages/ui/scripts/gen.mjs; do not edit) -->\n';
  for (const n of names) {
    const f = flavors[n];
    md += `### ${f.label} (\`data-gk-flavor="${n}"\`): ${f.use}\n\n${f.idea}\n\n`;
    md += `Fonts: ${f.fontFiles}\n\n| Token (\`--gk-color-*\`) | Light | Dark |\n|---|---|---|\n`;
    for (const k of Object.keys(f.light)) md += `| ${k} | \`${f.light[k]}\` | \`${f.dark[k]}\` |\n`;
    md += `\n| Scale | Values |\n|---|---|\n`;
    md += `| font (\`--gk-font-*\`) | ${Object.entries(f.font).map(([k, v]) => `${k}: ${v.split(',')[0]}`).join('; ')} |\n`;
    md += `| text (\`--gk-text-*\`) | ${Object.entries(f.text).map(([k, v]) => `${k} ${v}`).join(', ')} |\n`;
    md += `| leading | ${Object.entries(f.leading).map(([k, v]) => `${k} ${v}`).join(', ')} |\n`;
    md += `| weight | ${Object.entries(f.weight).map(([k, v]) => `${k} ${v}`).join(', ')} |\n`;
    md += `| radius (\`--gk-radius-*\`) | ${Object.entries(f.radius).map(([k, v]) => `${k} ${v}`).join(', ')} |\n`;
    md += `| control height | ${f['control-h']} (min ${shared['touch-min']} on touch) |\n\n`;
    const rem = (v) => Math.round(parseFloat(v) * 16);
    const py = {
      name: n,
      font: f.python,
      size: Object.fromEntries(Object.entries(f.text).map(([k, v]) => [k, rem(v)])),
      radius: Object.fromEntries(Object.entries(f.radius).filter(([k]) => k !== 'full').map(([k, v]) => [k, rem(v)])),
      control_h: rem(f['control-h']),
      light: Object.fromEntries(Object.entries(f.light).filter(([k]) => !['overlay', 'shadow-color'].includes(k)).map(([k, v]) => [k.replace(/-/g, '_'), v])),
      dark: Object.fromEntries(Object.entries(f.dark).filter(([k]) => !['overlay', 'shadow-color'].includes(k)).map(([k, v]) => [k.replace(/-/g, '_'), v])),
    };
    md += `Python theme dict (sizes in px):\n\n\`\`\`python\nGK_${n.toUpperCase()} = ${JSON.stringify(py, null, 4).replace(/\btrue\b/g, 'True').replace(/\bfalse\b/g, 'False')}\n\`\`\`\n\n`;
  }
  md += `### Shared (all flavors)\n\n| Group | Values |\n|---|---|\n`;
  md += `| space (\`--gk-space-*\`) | ${Object.entries(shared.space).map(([k, v]) => `${k}=${v}`).join(', ')} |\n`;
  md += `| motion | ${Object.entries(shared.motion).map(([k, v]) => `\`--gk-${k}\` ${v}`).join('; ')} |\n`;
  md += `| z-index (\`--gk-z-*\`) | ${Object.entries(shared.z).map(([k, v]) => `${k} ${v}`).join(', ')} |\n`;
  md += `| touch target | ${shared['touch-min']} (44px) minimum on coarse pointers |\n| reading measure | ${shared.measure} |\n`;
  return md + '<!-- RAW:END -->';
}

const norm = (s) => s.replace(/\r\n/g, '\n');
const brief = here('../../../docs/DESIGN-BRIEF.md');
const outputs = [
  [here('../src/v2/tokens.css'), tokensCss()],
  [here('../src/v2/tailwind.css'), tailwindCss()],
  [here('../src/v2/flavors.ts'), flavorsTs()],
];
if (existsSync(brief)) {
  const cur = norm(readFileSync(brief, 'utf8'));
  const next = cur.replace(/<!-- RAW:START[\s\S]*?<!-- RAW:END -->/, briefBlock());
  outputs.push([brief, next]);
}

const check = process.argv.includes('--check');
let drift = 0;
for (const [url, text] of outputs) {
  const cur = existsSync(url) ? norm(readFileSync(url, 'utf8')) : null;
  if (cur === text) continue;
  if (check) { drift++; console.log(`out of date: ${url.pathname}`); } else { writeFileSync(url, text); console.log(`wrote ${url.pathname}`); }
}
if (check && drift) { console.log('run: npm run gen -w @gokulsaraswat/ui'); process.exitCode = 1; }
