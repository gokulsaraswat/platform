#!/usr/bin/env bash
# Keeps the agent kit identical across all repos under Project/.
#   sync-kit.sh                check only (read-only report)
#   sync-kit.sh --fix          copy RULES.md, add RULES.md pointer to AGENTS/CLAUDE, create missing BACKLOG.md
#   sync-kit.sh --index        regenerate cross-repo index in platform/docs/BACKLOG.md
#   sync-kit.sh --push         commit + push ONLY kit files in each repo (never other dirty files)
#   sync-kit.sh --install-hooks  add warn-only pre-push hook to each repo
set -euo pipefail

HERE="$(cd "$(dirname "$0")" && pwd)"
PLATFORM="$(cd "$HERE/.." && pwd)"
ROOT="$(cd "$PLATFORM/.." && pwd)"
RULES="$PLATFORM/docs/RULES.md"
TEMPLATE="$PLATFORM/docs/BACKLOG-TEMPLATE.md"
INDEX="$PLATFORM/docs/BACKLOG.md"

REPOS=(platform admin gokulmobilize bestportofolio Progress Markdown-studio checkers-gym-management gokul-omni-converter)
prefix() {
  case "$1" in
    platform) echo PLT;; admin) echo ADM;; gokulmobilize) echo MOB;; bestportofolio) echo PRT;;
    Progress) echo GSP;; Markdown-studio) echo MDS;; checkers-gym-management) echo GYM;; gokul-omni-converter) echo OMN;;
  esac
}
KIT_FILES=(RULES.md AGENTS.md CLAUDE.md docs/ARCHITECTURE.md docs/BACKLOG.md)
MODE="${1:-check}"

check_repo() {
  local r="$1" d="$ROOT/$1" miss=() flags=()
  [[ -d "$d/.git" ]] || { echo "$r: not a git repo"; return; }
  [[ -f "$d/RULES.md" ]] && cmp -s "$RULES" "$d/RULES.md" || miss+=("RULES.md(stale/missing)")
  [[ -f "$d/docs/ARCHITECTURE.md" ]] || miss+=("docs/ARCHITECTURE.md")
  [[ -f "$d/docs/BACKLOG.md" ]] || miss+=("docs/BACKLOG.md")
  grep -qs 'RULES.md' "$d/AGENTS.md" || miss+=("AGENTS.md->RULES.md")
  grep -qs 'RULES.md' "$d/CLAUDE.md" || miss+=("CLAUDE.md->RULES.md")
  local dirty ahead behind
  dirty=$(git -C "$d" status --porcelain | wc -l | tr -d ' ')
  ahead=$(git -C "$d" rev-list --count '@{u}..HEAD' 2>/dev/null || echo "?")
  behind=$(git -C "$d" rev-list --count 'HEAD..@{u}' 2>/dev/null || echo "?")
  printf '%-26s dirty=%-3s ahead=%-2s behind=%-2s missing: %s\n' "$r" "$dirty" "$ahead" "$behind" "${miss[*]:-none}"
}

fix_repo() {
  local r="$1" d="$ROOT/$1" p; p="$(prefix "$1")"
  cp "$RULES" "$d/RULES.md"
  mkdir -p "$d/docs"
  if [[ ! -f "$d/docs/BACKLOG.md" ]]; then
    sed "s/<repo>/$r/;s/<PREFIX>/$p/" "$TEMPLATE" > "$d/docs/BACKLOG.md"
  fi
  grep -qs 'RULES.md' "$d/AGENTS.md" || printf '\nGlobal rules: read RULES.md first (synced from platform/docs/RULES.md). Backlog: docs/BACKLOG.md. Architecture: docs/ARCHITECTURE.md.\n' >> "$d/AGENTS.md"
  grep -qs 'RULES.md' "$d/CLAUDE.md" || printf '\n## Global rules\nRead `RULES.md` (synced from `platform/docs/RULES.md`) at the start of every session. It wins over anything above on commit/push, backlog, docs sync and privacy. Backlog: `docs/BACKLOG.md`.\n' >> "$d/CLAUDE.md"
}

build_index() {
  local out; out="$(mktemp)"
  {
    echo "<!-- INDEX:START (generated by scripts/sync-kit.sh --index; do not edit) -->"
    echo "## Cross-repo index (open P0/P1 and linked items)"
    echo "| Repo | ID | Title | Pri | Status | Needs/Blocks |"
    echo "|---|---|---|---|---|---|"
    for r in "${REPOS[@]}"; do
      [[ "$r" == platform ]] && continue
      f="$ROOT/$r/docs/BACKLOG.md"; [[ -f "$f" ]] || continue
      awk -F'|' -v repo="$r" '
        function t(s){gsub(/^ +| +$/,"",s);return s}
        /^\| [A-Z]+-[BIFXD]-[0-9]+/ {
          id=t($2); ti=t($3); pri=t($4); st=t($5); nd=t($6)
          if (st=="done"||st=="dropped") next
          if (pri=="P0"||pri=="P1"||nd!="") printf "| %s | %s | %s | %s | %s | %s |\n", repo,id,ti,pri,st,nd
        }' "$f"
    done
    echo "<!-- INDEX:END -->"
  } > "$out"
  if grep -q 'INDEX:START' "$INDEX" 2>/dev/null; then
    awk -v f="$out" '
      /<!-- INDEX:START/ {while((getline l < f)>0) print l; skip=1; next}
      /<!-- INDEX:END/ {skip=0; next}
      !skip {print}' "$INDEX" > "$INDEX.new" && mv "$INDEX.new" "$INDEX"
  else
    { sed -n '1,/^$/p' "$INDEX"; cat "$out"; echo; sed '1,/^$/d' "$INDEX"; } > "$INDEX.new" && mv "$INDEX.new" "$INDEX"
  fi
  rm -f "$out"; echo "index updated: $INDEX"
}

push_repo() {
  local r="$1" d="$ROOT/$1" paths=()
  for f in "${KIT_FILES[@]}"; do [[ -e "$d/$f" ]] && paths+=("$f"); done
  git -C "$d" fetch -q
  if [[ "$(git -C "$d" rev-list --count 'HEAD..@{u}' 2>/dev/null || echo 0)" != 0 ]]; then
    echo "$r: behind remote, skipped (pull --rebase first)"; return
  fi
  git -C "$d" add -- "${paths[@]}"
  if git -C "$d" diff --cached --quiet -- "${paths[@]}"; then echo "$r: kit already committed"
  else git -C "$d" commit -q -m "docs: sync agent kit (rules, backlog, architecture)" -- "${paths[@]}" && echo "$r: committed"; fi
  git -C "$d" push -q origin HEAD && echo "$r: pushed"
}

install_hooks() {
  local r="$1" d="$ROOT/$1" h="$ROOT/$1/.git/hooks/pre-push"
  [[ -f "$h" ]] && ! grep -q 'sync-kit pre-push' "$h" && cp "$h" "$h.bak.$(date +%s)"
  cat > "$h" <<'HOOK'
#!/bin/sh
# sync-kit pre-push (warn-only, never blocks)
top=$(git rev-parse --show-toplevel)
up=$(git rev-parse --abbrev-ref '@{u}' 2>/dev/null) || exit 0
changed=$(git diff --name-only "$up"..HEAD 2>/dev/null)
[ -z "$changed" ] && exit 0
echo "$changed" | grep -q '^WORKLOG.md$' || echo "warn: WORKLOG.md not updated in this push (RULES.md s5/s10)"
echo "$changed" | grep -q '^docs/BACKLOG.md$' || echo "warn: docs/BACKLOG.md not updated in this push (RULES.md s4)"
[ -f "$top/RULES.md" ] || echo "warn: RULES.md missing; run platform/scripts/sync-kit.sh --fix"
exit 0
HOOK
  chmod +x "$h"; echo "$r: hook installed"
}

case "$MODE" in
  check) for r in "${REPOS[@]}"; do check_repo "$r"; done ;;
  --fix) for r in "${REPOS[@]}"; do fix_repo "$r"; done; build_index; for r in "${REPOS[@]}"; do check_repo "$r"; done ;;
  --index) build_index ;;
  --push) for r in "${REPOS[@]}"; do push_repo "$r"; done ;;
  --install-hooks) for r in "${REPOS[@]}"; do install_hooks "$r"; done ;;
  *) echo "usage: $0 [check|--fix|--index|--push|--install-hooks]"; exit 1 ;;
esac
